"""Owner-approved, two-credit panel test; isolated from all production databases."""
import json
import os
import re
import sys
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from types import SimpleNamespace
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo

from replit_start import prepare_environment
from streambot.config import load_config
from streambot.panel import PanelClient,PanelError
from streambot.resellers import Resellers
from streambot.store import Store

ACTION=sys.argv[1]
if ACTION not in ('create','extend','status'):raise SystemExit('Unknown test stage')
config=load_config(env=prepare_environment(os.environ))
config.update(mode='live',telegram_enabled=False,encryption_key=os.environ['STREAMBOT_CREDENTIAL_KEY'])
uid=config['support_admin_id']
if not uid:raise SystemExit('Configured administrator is required')
store=Store('data/reseller-paid-probe.sqlite3',config['encryption_key'])


class BudgetPanel(PanelClient):
    def _request(self,method,path,**kwargs):
        route=urlsplit(self._url(path)).path.rstrip('/')
        kind=('create' if route.startswith('/lines/create') else
              'extend' if re.fullmatch(r'/lines/extend/[1-9][0-9]*',route) else None)
        if method.upper()=='POST' and kind:
            if kind!=ACTION:raise PanelError('This test stage does not authorise that action')
            data=kwargs.get('data') or {}
            try:price=Decimal(str(data.get('price')))
            except Exception:raise PanelError('Test price cannot be verified') from None
            if not price.is_finite() or not 0<price<=1:
                raise PanelError('Test price exceeds its approved per-action budget')
            if str(data.get('package'))!='137' or str(data.get('connections'))!='1':
                raise PanelError('Test package is not the approved one')
            if data.get('description')!='':raise PanelError('Test notes must be empty')
            if kind=='create' and (data.get('username')!='' or data.get('password')!=''):
                raise PanelError('Test credentials must be generated by the panel')
            if kind=='extend' and route!='/lines/extend/'+str(store.metadata('probe:provider_id')):
                raise PanelError('Cannot extend any account except the newly created test account')
            with store.connection() as db:
                db.execute('BEGIN IMMEDIATE')
                rows=db.execute("SELECT key,value FROM metadata WHERE key IN ('probe:submitted:create','probe:submitted:extend')").fetchall()
                if any(row['key']=='probe:submitted:'+kind for row in rows):
                    raise PanelError('This action was already attempted; reconciliation only')
                spent=sum((Decimal(json.loads(row['value'])['price']) for row in rows),Decimal(0))
                if spent+price>2:raise PanelError('Approved total test budget exceeded')
                db.execute('INSERT INTO metadata(key,value) VALUES(?,?)',
                           ('probe:submitted:'+kind,json.dumps({'price':str(price),'route':route})))
            # The submission intent is durable before any remote business POST.
        return super()._request(method,path,**kwargs)


panel=BudgetPanel(config['panel_base_url'],config['panel_username'],config['panel_password'],allow_create=True)
service=SimpleNamespace(config=config,store=store,panel=panel)
resellers=Resellers(service)
finance,ops=resellers.finance,resellers.ops


def balance():
    soup,form,_=panel._create_form()
    raw=panel._form_data(form).get('credits_left')
    if not raw:
        scripts='\n'.join(s.get_text() for s in soup.select('script'))
        values=re.findall(r'\b(?:var|let|const)\s+currentCredits\s*=\s*(\d+(?:\.\d+)?)\s*-\s*credits',scripts)
        if len(values)!=1:raise PanelError('Cannot verify panel credit balance')
        raw=values[0]
    value=Decimal(str(raw))
    if not value.is_finite():raise PanelError('Invalid panel balance')
    return value


def run():
    if ACTION!='status':
        if not store.metadata('probe:balance_initial'):
            store.metadata('probe:balance_initial',str(balance()))
        finance.account_status(uid,uid,'active','Owner-approved isolated integration test')
        finance.adjust(uid,uid,2,'Non-cash test allowance in isolated local database only','approved-two-credit-probe')
        if ACTION=='create':
            preview=ops.preview(uid,'create',1,1,False,'Owner-approved provider test')
        else:
            sid=store.metadata('probe:subscription_id')
            if not sid:raise PanelError('Creation must be confirmed before extension')
            original=Decimal(store.metadata('probe:balance_initial'))
            if original-balance()!=1:raise PanelError('Panel balance changed unexpectedly; stop before extension')
            ops.refresh(uid,sid)
            preview=ops.preview(uid,'extend',1,1,False,target=sid)
        op=ops.reserve(uid,'owner-approved-live-probe-'+ACTION,preview)
        if op['status']=='queued':
            with store.connection() as db:
                queued=db.execute("SELECT id FROM rs_operations WHERE status='queued'").fetchall()
            if len(queued)!=1 or queued[0]['id']!=op['id']:raise PanelError('Unexpected queued requests')
            ops.process()
        op=ops.operation(uid,op['id'])
        if op['status']=='succeeded':
            record=ops.owned(uid,op['result_id'])
            store.metadata('probe:provider_id',record['provider_id'])
            store.metadata('probe:subscription_id',record['id'])
            if not store.metadata('probe:original_credentials'):
                store.metadata('probe:original_credentials',record['credentials'])
        if op['status']!='succeeded':
            print(json.dumps({'stage':ACTION,'status':op['status'],'reservation':op['reservation'],
                              'automatic_retry':False,'production_database_untouched':True}))
            return
    sid=store.metadata('probe:subscription_id')
    if not sid:raise PanelError('No confirmed test account')
    record,warning,extensions=ops.refresh(uid,sid)
    if warning:raise PanelError('Provider read-back cannot be confirmed')
    first=store.unseal(store.metadata('probe:original_credentials'))
    if isinstance(first,str):first=store.unseal(first)
    with store.connection() as db:
        operations=[dict(r) for r in db.execute('SELECT operation_type,status,credit_cost,reservation FROM rs_operations ORDER BY created_at,id').fetchall()]
    result=dict(stage=ACTION,provider_id=record['provider_id'],kind=record['kind'],
                connections=record['connections'],adult=bool(record['adult']),status=record['status'],
                expiry_london=datetime.fromtimestamp(record['expires_at'],ZoneInfo('Europe/London')).isoformat(),
                same_credentials=all(record['credentials'][k]==first[k] for k in ('username','password')),
                extension_count=len(extensions),operations=operations,
                isolated_test_balance=finance.member(uid)['balance'],
                isolated_test_reserved=finance.member(uid)['reserved'],
                panel_balance_delta_since_start=str(Decimal(store.metadata('probe:balance_initial'))-balance()),
                production_database_untouched=True,credentials_not_printed=True)
    if extensions:
        result['previous_expiry_london']=datetime.fromtimestamp(extensions[0]['previous_expiry'],ZoneInfo('Europe/London')).isoformat()
        result['extension_retained_existing_time']=extensions[0]['confirmed_expiry']>extensions[0]['previous_expiry']
    Path('data/reseller-paid-probe-result.json').write_text(json.dumps(result,indent=2))
    print(json.dumps(result))


try:run()
except Exception as exc:
    print(json.dumps({'stage':ACTION,'error_type':type(exc).__name__,'automatic_retry':False,
                      'production_database_untouched':True,'credentials_not_printed':True}))
    raise SystemExit(1)
finally:
    for path in Path('data').glob('reseller-paid-probe*'):
        if path.is_file():path.chmod(0o600)
